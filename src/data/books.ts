function toBook(seed: BookSeed): Book {
  const seller = sellerById(seed.sellerId);
  return {
    id: seed.id,
    title: seed.title,
    author: seed.author,
    isbn: `978-${String(1000000000 + seed.id.length * 7919 + seed.pages * 13).slice(0, 10)}`,
    edition: seed.edition,
    publisher: seed.publisher,
    subject: seed.subject,
    courseCodes: seed.courseCodes,
    language: 'English',
    pages: seed.pages,
    condition: seed.condition,
    transaction: seed.transaction,
    price: { amount: seed.price, currency: 'INR' },
    retailPrice: seed.retail ? { amount: seed.retail, currency: 'INR' } : undefined,
    coverImage: photo(seed.cover, { w: 640, h: 900 }),
    description: seed.description,
    seller,
    location: seed.location,
    fulfilment: seed.fulfilment,
    status: seed.status ?? 'active',
    createdAt: rel.days(seed.ageDays),
    origin: 'demo',
    tags: seed.tags,
    reported: seed.reported,
  };
}

